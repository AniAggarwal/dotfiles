-- Dune theme colors (generated by matugen into ~/.config/themes/current).
-- Parse the `$name = rgba(...)` lines so border/shadow colors follow the wallpaper.
-- Falls back to the previous hardcoded values if the file is missing.
local theme_colors = {}
do
    local f = io.open(os.getenv("HOME") .. "/.config/themes/current/colors-hyprland.conf", "r")
    if f then
        for line in f:lines() do
            local name, value = line:match("^%s*%$([%w_]+)%s*=%s*(rgba?%b())")
            if name and value then
                theme_colors[name] = value
            end
        end
        f:close()
    end
end
local function tc(name, fallback)
    return theme_colors[name] or fallback
end

