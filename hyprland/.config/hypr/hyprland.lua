local function enable_laptop_monitor()
    hl.monitor({
        output = "eDP-1",
        disabled = false,
        mode = "3456x2160@60",
        position = "0x0",
        scale = "1.5",
        bitdepth = 10,
        cm = "srgb",
        sdr_eotf = "srgb",
        supports_wide_color = 1,
        supports_hdr = 1,
    })
end

local function lid_is_closed()
    local f = io.open("/proc/acpi/button/lid/LID0/state", "r")
    if not f then
        return false
    end

    local state = f:read("*a")
    f:close()
    return state:match("closed") ~= nil
end

if lid_is_closed() then
    hl.monitor({ output = "eDP-1", disabled = true })
else
    enable_laptop_monitor()
end

-- Called via `hyprctl eval` from hypridle's after_sleep_cmd (see ~/.config/hypr/hypridle.conf):
-- resuming from suspend/hibernate otherwise leaves eDP-1 blank until a reload.
function _G.on_resume()
    if lid_is_closed() then
        hl.monitor({ output = "eDP-1", disabled = true })
    else
        enable_laptop_monitor()
    end
end

